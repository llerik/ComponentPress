from pathlib import Path
from typing import Callable, ContextManager, Protocol

from componentpress.domain.component import ComponentDefinition
from componentpress.domain.diagnostics import Diagnostic
from componentpress.domain.project import DataSource, ProjectDefinition
from componentpress.domain.render_plan import ResolvedComponent
from componentpress.domain.values import DataRow, DataSheetSnapshot
from .contracts import BuildInputSnapshot, BuildProgress, BuildResult, DocumentSnapshot, FileFingerprint, ProjectSnapshot, RenderResult


class Cancellation(Protocol):
    @property
    def cancelled(self) -> bool: ...

    def cancel(self) -> None: ...

    def check(self) -> None: ...


class ProjectRepository(Protocol):
    def create(self, root: Path, name: str) -> ProjectSnapshot: ...
    def open(self, root: Path) -> ProjectSnapshot: ...
    def migrate(self, root: Path) -> ProjectSnapshot: ...
    def save_project(self, snapshot: ProjectSnapshot, **changes: object) -> ProjectSnapshot: ...
    def save_component(self, snapshot: ProjectSnapshot, component_id: str, **changes: object) -> ProjectSnapshot: ...
    def prepare_component(self, snapshot: ProjectSnapshot, component_id: str, model: ComponentDefinition, base: DocumentSnapshot | None = None) -> DocumentSnapshot: ...
    def prepare_text(self, snapshot: ProjectSnapshot, component_id: str, text: str) -> DocumentSnapshot: ...
    def save_prepared(self, snapshot: ProjectSnapshot, component_id: str, document: DocumentSnapshot) -> ProjectSnapshot: ...
    def add_component(self, snapshot: ProjectSnapshot, component_id: str, name: str, **values: object) -> ProjectSnapshot: ...
    def remove_component(self, snapshot: ProjectSnapshot, component_id: str, *, backup_path: str): ...
    def restore_component(self, snapshot: ProjectSnapshot, component_id: str, **values: object) -> ProjectSnapshot: ...


class ResourceRepository(Protocol):
    def import_image(self, root: Path, source: Path, folder: str = "") -> str: ...
    def import_data(self, root: Path, source: Path) -> str: ...


class ArchiveRepository(Protocol):
    """Project-version archive contract, separate from PNG build archives."""
    def export(self, snapshot: ProjectSnapshot, target: Path, *, replace: bool = False, cancellation=None, on_progress=None) -> tuple[Path, str, bool, str | None]: ...
    def restore_path(self, archive_path: Path, destination: Path, *, cancellation=None, on_progress=None) -> Path: ...


class DataSourceReader(Protocol):
    def read(
        self, path: Path, sheet: str, *, source: str = "main",
        id_column: str | None = None, copies_column: str | None = None,
        version: int = 1, request_id: int = 0, data: bytes | None = None,
        copies_columns: tuple[str, str] | None = None,
    ) -> DataSheetSnapshot: ...


class ComponentResolver(Protocol):
    def validate_columns(self, component: ComponentDefinition, data: DataSheetSnapshot, *, owner: Path | None = None) -> None: ...
    def validate_static_resources(self, component: ComponentDefinition, *, owner: Path | None = None) -> None: ...
    def resolve_component(
        self, component: ComponentDefinition, data: DataSheetSnapshot | None,
        row: DataRow | None, *, owner: Path | None = None,
    ) -> ResolvedComponent: ...


class ValidationStateStore(Protocol):
    def canonical_root(self, root: Path) -> Path: ...
    def source_path(self, root: Path, relative_path: str) -> Path: ...
    def fingerprint(self, path: Path) -> FileFingerprint: ...
    def store_validation(
        self, root: Path, source_path: str, fingerprint: FileFingerprint,
        component_ids: list[str],
    ) -> Diagnostic | None: ...


class BindingResolverFactory(Protocol):
    def __call__(
        self, root: Path, project: ProjectDefinition, *, validate_resources: bool = True,
    ) -> ComponentResolver: ...


class ComponentRenderer(Protocol):
    def __call__(
        self, snapshot: ProjectSnapshot, component_id: str, output: Path, *,
        component: ComponentDefinition | None = None, dpi: int | None = None,
    ) -> RenderResult: ...


class BuildRunner(Protocol):
    def start(
        self,
        snapshot: BuildInputSnapshot,
        on_progress: Callable[[BuildProgress], None] | None = None,
        on_finished: Callable[[BuildResult], None] | None = None,
    ) -> str: ...

    def cancel(self, job_id: str) -> bool: ...

    def is_active(self, job_id: str | None = None) -> bool: ...


WriteLockFactory = Callable[[Path], ContextManager[object]]
